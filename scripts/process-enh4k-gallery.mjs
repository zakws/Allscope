/**
 * Gallery pipeline for the ALLSCOPE_ENHANCED_4K collection.
 *
 * Reads scripts/gallery-selection.json — the curated, ORDERED selection:
 *   [{ file, alt, caption?, role: "featured" | "support" | "row",
 *      replacement? }]
 * (order in the array IS the display order; first entry is the featured
 * opener, the next 2-3 "support" sit directly under it).
 *
 * `replacement` names a file in ALLSCOPE-ENHANCED-REPLACEMENTS-2026-08-30
 * (enhanced versions of soft masters, supplied 30 Aug 2026): it is used as
 * the pixel source while the output name and URLs stay keyed to `file`.
 *
 * Emits per photo:
 *   public/media/gallery/thumb/<name>.webp  (grid, 1000px long edge, q80)
 *   public/media/gallery/full/<name>.webp   (lightbox, 2400px long edge, q84)
 * and regenerates src/content/gallery-data.gen.ts.
 *
 * Masters in ALLSCOPE_ENHANCED_4K are never modified.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const sharp = require("sharp");

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SITE = path.resolve(HERE, "..");
const SRC = path.resolve(SITE, "..", "ALLSCOPE_ENHANCED_4K_V2", "ALLSCOPE_ENHANCED_4K");
const REPL = path.resolve(SITE, "..", "ALLSCOPE-ENHANCED-REPLACEMENTS-2026-08-30");
const OUT_T = path.join(SITE, "public", "media", "gallery", "thumb");
const OUT_F = path.join(SITE, "public", "media", "gallery", "full");

const selection = JSON.parse(
  fs.readFileSync(path.join(HERE, "gallery-selection.json"), "utf8"),
);

// Fresh output dirs: the gallery is fully derived from the selection.
fs.rmSync(path.join(SITE, "public", "media", "gallery"), { recursive: true, force: true });
fs.mkdirSync(OUT_T, { recursive: true });
fs.mkdirSync(OUT_F, { recursive: true });

const records = [];
for (const item of selection) {
  const srcPath = item.replacement ? path.join(REPL, item.replacement) : path.join(SRC, item.file);
  if (!fs.existsSync(srcPath)) throw new Error(`missing source: ${item.replacement ?? item.file}`);
  const name = item.file
    .replace(/_ALLSCOPE_4K\.jpg$/i, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-");

  const img = sharp(srcPath).rotate();
  const meta = await img.metadata();
  const landscape = (meta.width ?? 1) >= (meta.height ?? 1);
  const resizeT = landscape ? { width: 1000 } : { height: 1000 };
  const resizeF = landscape ? { width: 2400 } : { height: 2400 };

  await img.clone().resize({ ...resizeT, withoutEnlargement: true }).webp({ quality: 80, effort: 5 }).toFile(path.join(OUT_T, `${name}.webp`));
  await img.clone().resize({ ...resizeF, withoutEnlargement: true }).webp({ quality: 84, effort: 5 }).toFile(path.join(OUT_F, `${name}.webp`));

  const t = await sharp(path.join(OUT_T, `${name}.webp`)).metadata();
  records.push({
    thumb: `/media/gallery/thumb/${name}.webp`,
    full: `/media/gallery/full/${name}.webp`,
    width: t.width,
    height: t.height,
    orientation: landscape ? "landscape" : "portrait",
    alt: item.alt,
    ...(item.caption ? { caption: item.caption } : {}),
    role: item.role ?? "row",
  });
}

const ts = `/**
 * GENERATED by scripts/process-enh4k-gallery.mjs from the curated selection in
 * scripts/gallery-selection.json (ALLSCOPE_ENHANCED_4K collection, all 222
 * photographs reviewed; this file holds the ordered gallery picks only).
 * Do not edit by hand; edit the selection and re-run the script.
 */

export interface GalleryPhoto {
  thumb: string;
  full: string;
  width: number;
  height: number;
  orientation: "landscape" | "portrait";
  alt: string;
  caption?: string;
  role: "featured" | "support" | "row";
}

export const galleryPhotos: GalleryPhoto[] = ${JSON.stringify(records, null, 2)};
`;
fs.writeFileSync(path.join(SITE, "src", "content", "gallery-data.gen.ts"), ts, "utf8");

const size = (d) => fs.readdirSync(d).reduce((a, f) => a + fs.statSync(path.join(d, f)).size, 0);
console.log(`gallery: ${records.length} photos`);
console.log(`thumbs: ${(size(OUT_T) / 1048576).toFixed(1)} MB · full: ${(size(OUT_F) / 1048576).toFixed(1)} MB`);
