/**
 * Feature photos for the high-visibility slots (homepage, capabilities,
 * about, safety, tenders), cut from the ALLSCOPE_ENHANCED_4K_V2 remaster
 * (q95 masters, overlays repaired). Every pick was scored in the full
 * 222-photo review; alts are written from what each frame actually shows.
 *
 * Emits public/media/features/<slot>.webp (2400px long edge, q84) and
 * src/content/capability-data.gen.ts. Masters untouched.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const sharp = require("sharp");

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SITE = path.resolve(HERE, "..");
const SRC = path.resolve(SITE, "..", "ALLSCOPE_ENHANCED_4K_V2", "ALLSCOPE_ENHANCED_4K");
const OUT = path.join(SITE, "public", "media", "features");

const P = "PHOTO-2026-07-29-";
const SLOTS = [
  ["home-band", P + "18-33-41(29)_ALLSCOPE_4K.jpg",
   "Allscope boom pump raised between two Allscope branded trucks beside a freshly finished slab"],
  ["home-slab", P + "20-58-22_ALLSCOPE_4K.jpg",
   "Freshly finished commercial ground slab with column starter cages and a trowel operator working the far edge"],
  ["cap-placement", P + "20-56-25(2)_ALLSCOPE_4K.jpg",
   "Wide suspended slab pour with the boom pump overhead and a power trowel operator in the foreground"],
  ["cap-finishing", P + "18-33-26_ALLSCOPE_4K.jpg",
   "Crew screeding and trowelling a broad freshly poured basement ramp slab"],
  ["cap-pumping", P + "18-33-41(24)_ALLSCOPE_4K.jpg",
   "Two agitator trucks feeding an Allscope branded boom pump at sunset while the crew places concrete"],
  ["cap-prepour", P + "20-56-54(2)_ALLSCOPE_4K.jpg",
   "Beam cages and top reinforcement fixed over metal deck formwork on a large suspended slab"],
  ["cap-planning", P + "18-23-09(11)_ALLSCOPE_4K.jpg",
   "Tower crane rising from a formed lift core above a basement raft prepared with membrane and starter cages"],
  ["cap-band", "IMG_1040_ALLSCOPE_4K.jpg",
   "Aerial view of a large basement raft pour with two concrete pump booms, queued agitator trucks and crews spreading concrete"],
  ["about-pour", P + "20-58-20_ALLSCOPE_4K.jpg",
   "Concreting crew working the wet edge of a large commercial slab pour over mesh reinforcement"],
  ["about-completed", P + "20-56-49_ALLSCOPE_4K.jpg",
   "Curved freshly finished concrete path with a broom finish running through a landscaped garden"],
  ["safety-crew", P + "20-58-17(1)_ALLSCOPE_4K.jpg",
   "Harnessed concreters screeding wet concrete along a narrow elevated walkway between timber edge forms"],
  ["safety-trowel", P + "20-58-22(2)_ALLSCOPE_4K.jpg",
   "Two ride-on trowel operators finishing a large fresh commercial slab around column starter cages"],
  ["safety-slab", "IMG_1033_ALLSCOPE_4K.jpg",
   "Ride-on power trowel on a freshly finished concrete slab with starter bars along the perimeter wall"],
  ["tenders-deck", P + "20-56-56(2)_ALLSCOPE_4K.jpg",
   "Reinforced deck laid with mesh ready for concrete, with the pour underway in the distance"],
];

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

const records = {};
for (const [slot, file, alt] of SLOTS) {
  const p = path.join(SRC, file);
  if (!fs.existsSync(p)) throw new Error("missing master: " + file);
  const img = sharp(p).rotate();
  const meta = await img.metadata();
  const landscape = (meta.width ?? 1) >= (meta.height ?? 1);
  await img
    .resize(landscape ? { width: 2400 } : { height: 2400 })
    .webp({ quality: 84, effort: 5 })
    .toFile(path.join(OUT, `${slot}.webp`));
  const m = await sharp(path.join(OUT, `${slot}.webp`)).metadata();
  records[slot] = { src: `/media/features/${slot}.webp`, width: m.width, height: m.height, alt };
}

const ts = `/**
 * GENERATED by scripts/process-v2-features.mjs from ALLSCOPE_ENHANCED_4K_V2.
 * Feature photography for the homepage, capabilities, about, safety and
 * tender pages. Do not edit by hand; edit the slot table and re-run.
 */

export interface FeaturePhoto {
  src: string;
  width: number;
  height: number;
  alt: string;
}

export const featurePhotos = ${JSON.stringify(records, null, 2)} as const satisfies Record<string, FeaturePhoto>;

export type FeatureSlot = keyof typeof featurePhotos;
`;
fs.writeFileSync(path.join(SITE, "src", "content", "capability-data.gen.ts"), ts, "utf8");
const size = fs.readdirSync(OUT).reduce((a, f) => a + fs.statSync(path.join(OUT, f)).size, 0);
console.log(`${SLOTS.length} feature photos, ${(size / 1048576).toFixed(1)} MB`);
